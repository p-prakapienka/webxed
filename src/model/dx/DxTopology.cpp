DxTopology::DxTopology(int algorithm)
    : algorithm_(std::clamp(algorithm, 0, algorithmCount - 1)) {}

int DxTopology::getAlgorithm() const {
    return algorithm_;
}

bool DxTopology::isCarrier(int op) const {
    return (flagsFor(algorithm_, op) & 0x04) != 0;
}

bool DxTopology::isFeedbackOperator(int op) const {
    return (flagsFor(algorithm_, op) & 0xc0) == 0xc0;
}

int DxTopology::getInputBus(int op) const {
    return (flagsFor(algorithm_, op) >> 4) & 3;
}

int DxTopology::getOutputBus(int op) const {
    return flagsFor(algorithm_, op) & 3;
}

int DxTopology::getOpNumber(int index) {
    return 6 - index;
}

std::string DxTopology::getOpLabel(int index) {
    return "DX OP" + std::to_string(getOpNumber(index));
}

int DxTopology::flagsFor(int algorithm, int op) {
    const int safeAlgorithm = std::clamp(algorithm, 0, algorithmCount - 1);
    const int safeOp = std::clamp(op, 0, operatorCount - 1);
    return dxAlgorithms[static_cast<std::size_t>(safeAlgorithm)][static_cast<std::size_t>(safeOp)];
}
